# Amdir Music Player - Windows playlist updater (WoW 3.3.5a, PowerShell 2.0+).
# Music lives in AddOns\AmdirMusicLibrary so that updating AmdirMusicPlayer
# through the Amdir AddOns Downloader never deletes your songs.
$ErrorActionPreference = 'Stop'
$addonDir = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$libraryName = 'AmdirMusicLibrary'
$libraryDir = Join-Path (Split-Path -Parent $addonDir) $libraryName
$musicDir = Join-Path $libraryDir 'Music'
$cacheDir = Join-Path $libraryDir 'MusicCache'
$output = Join-Path $libraryDir 'Playlist.lua'
$utf8 = New-Object System.Text.UTF8Encoding($false)
Write-Host ('Music library: ' + $libraryDir)

foreach ($dir in @($libraryDir, $musicDir, $cacheDir)) {
    if (-not (Test-Path -LiteralPath $dir -PathType Container)) { New-Item -ItemType Directory -Path $dir | Out-Null }
}
$toc = "## Interface: 30300`n## Title: Amdir |cff6fd3ffMusic Library|r`n## Notes: Your music for Amdir Music Player (generated by UpdatePlaylist)`n## Author: Amdir`n## Version: 1`nPlaylist.lua`n"
[System.IO.File]::WriteAllText((Join-Path $libraryDir ($libraryName + '.toc')), $toc, $utf8)
$readme = "Put your MP3 or OGG files in this folder (subfolders are supported).`r`nThen run UpdatePlaylist.bat in Interface\AddOns\AmdirMusicPlayer and fully restart WoW.`r`n"
[System.IO.File]::WriteAllText((Join-Path $musicDir 'PUT_MUSIC_HERE.txt'), $readme, $utf8)

# Move music from the old layout (AmdirMusicPlayer\Music) into the library.
$oldMusic = Join-Path $addonDir 'Music'
if (Test-Path -LiteralPath $oldMusic -PathType Container) {
    foreach ($item in @(Get-ChildItem -LiteralPath $oldMusic -Force)) {
        if ($item.Name -eq 'PUT_MUSIC_HERE.txt') { Remove-Item -LiteralPath $item.FullName -Force; continue }
        $target = Join-Path $musicDir $item.Name
        if (Test-Path -LiteralPath $target) { Write-Host ('NOT MOVED (already exists): ' + $item.Name); continue }
        Write-Host ('Moving to library: ' + $item.Name)
        Move-Item -LiteralPath $item.FullName -Destination $target
    }
    if (@(Get-ChildItem -LiteralPath $oldMusic -Force).Count -eq 0) { Remove-Item -LiteralPath $oldMusic -Force }
}
$oldCache = Join-Path $addonDir 'MusicCache'
if (Test-Path -LiteralPath $oldCache) { Remove-Item -LiteralPath $oldCache -Recurse -Force }
$oldPlaylist = Join-Path $addonDir 'Playlist.lua'
if (Test-Path -LiteralPath $oldPlaylist) { Remove-Item -LiteralPath $oldPlaylist -Force }

function ToLua([string]$x) {
    return '"' + $x.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t') + '"'
}

# WoW fonts lack Latin diacritics (e.g. z with caron): turn them into plain letters.
function WowTitle([string]$x) {
    $sb = New-Object System.Text.StringBuilder
    foreach ($ch in $x.ToCharArray()) {
        $code = [int]$ch
        if ($code -ge 0xC0 -and $code -le 0x24F) {
            $plain = ([string]$ch).Normalize([System.Text.NormalizationForm]::FormD)
            $base = ''
            foreach ($c in $plain.ToCharArray()) {
                if ([System.Globalization.CharUnicodeInfo]::GetUnicodeCategory($c) -ne [System.Globalization.UnicodeCategory]::NonSpacingMark) { $base += $c }
            }
            if ($base.Length -gt 0 -and [int]$base[0] -lt 128) { [void]$sb.Append($base) } else { [void]$sb.Append($ch) }
        } else {
            [void]$sb.Append($ch)
        }
    }
    return $sb.ToString()
}

# Copy a file without its leading ID3v2 tag (broken tags make WoW stay silent).
function CopyWithoutId3([string]$src, [string]$dest) {
    $in = [System.IO.File]::OpenRead($src)
    try {
        $head = New-Object byte[] 10
        $read = $in.Read($head, 0, 10)
        $skip = 0
        if ($read -eq 10 -and $head[0] -eq 0x49 -and $head[1] -eq 0x44 -and $head[2] -eq 0x33) {
            $skip = 10 + ($head[6] * 2097152) + ($head[7] * 16384) + ($head[8] * 128) + $head[9]
            if ($head[5] -band 0x10) { $skip += 10 }
        }
        if ($skip -ge $in.Length) { $skip = 0 }
        $in.Position = $skip
        $out = [System.IO.File]::Create($dest)
        try {
            $buffer = New-Object byte[] 1048576
            while (($n = $in.Read($buffer, 0, $buffer.Length)) -gt 0) { $out.Write($buffer, 0, $n) }
        } finally { $out.Close() }
    } finally { $in.Close() }
}

Write-Host 'Scanning music...'
# Track length from Windows metadata (System.Media.Duration, 100 ns units).
$shell = $null
try { $shell = New-Object -ComObject Shell.Application } catch { }
function DurationSeconds($file) {
    if ($shell -eq $null) { return 0 }
    try {
        $folder = $shell.Namespace($file.DirectoryName)
        $item = $folder.ParseName($file.Name)
        $ticks = $item.ExtendedProperty('System.Media.Duration')
        if ($ticks) { return [math]::Round([double]$ticks / 10000000, 2) }
    } catch { }
    return 0
}

$folders = @(Get-ChildItem -LiteralPath $musicDir -Recurse | Where-Object { $_.PSIsContainer } | Sort-Object FullName)
$files = @(Get-ChildItem -LiteralPath $musicDir -Recurse | Where-Object { -not $_.PSIsContainer -and $_.Extension -match '^\.(mp3|ogg)$' } | Sort-Object FullName)
# Only purge our own generated cache aliases.
Get-ChildItem -LiteralPath $cacheDir | Where-Object { -not $_.PSIsContainer -and $_.Name -match '^track_.*\.(mp3|ogg)$' } | ForEach-Object { Remove-Item -LiteralPath $_.FullName -Force }

$lines = New-Object 'System.Collections.Generic.List[string]'
$lines.Add('-- Generated automatically by UpdatePlaylist.ps1 (UTF-8, without BOM).')
$lines.Add('AmdirMusicFolders = {')
foreach ($folder in $folders) {
    $rel = $folder.FullName.Substring($musicDir.Length).TrimStart([char[]]@('\', '/')).Replace('\', '/')
    $index = $rel.LastIndexOf('/')
    $parent = if ($index -ge 0) { $rel.Substring(0, $index) } else { '' }
    $lines.Add('    { path = ' + (ToLua $rel) + ', parent = ' + (ToLua $parent) + ', name = ' + (ToLua $folder.Name) + ' },')
}
$lines.Add('}')
$lines.Add('AmdirMusicTracks = {')
$i = 0
foreach ($file in $files) {
    $i = $i + 1
    $relative = $file.FullName.Substring($musicDir.Length).TrimStart([char[]]@('\', '/')).Replace('\', '/')
    $idx = $relative.LastIndexOf('/')
    $parent = if ($idx -ge 0) { $relative.Substring(0, $idx) } else { '' }
    $suffix = $file.Extension.ToLowerInvariant()
    $alias = 'track_{0:D5}{1}' -f $i, $suffix
    $dest = Join-Path $cacheDir $alias
    Write-Host ('[' + $i + '/' + $files.Count + '] ' + $relative)
    if ($suffix -eq '.mp3') { CopyWithoutId3 $file.FullName $dest } else { Copy-Item -LiteralPath $file.FullName -Destination $dest }
    $duration = DurationSeconds $file
    $gamePath = 'Interface\AddOns\' + $libraryName + '\MusicCache\' + $alias
    $durationText = ([double]$duration).ToString([System.Globalization.CultureInfo]::InvariantCulture)
    $lines.Add('    { title = ' + (ToLua (WowTitle $file.BaseName)) + ', path = ' + (ToLua $gamePath) + ', folder = ' + (ToLua $parent) + ', duration = ' + $durationText + ' },')
}
$lines.Add('}')
[System.IO.File]::WriteAllText($output, [string]::Join("`n", $lines.ToArray()) + "`n", $utf8)

Write-Host ''
Write-Host ('Tracks found: ' + $files.Count + '; Folders found: ' + $folders.Count)
Write-Host ('Music folder: ' + $musicDir)
Write-Host ('Saved: ' + $output)
if ($files.Count -eq 0) {
    Write-Host 'Add MP3/OGG files to the Music folder (it opens now) and run UpdatePlaylist.bat again.'
    Start-Process explorer.exe -ArgumentList ('"' + $musicDir + '"')
}
Write-Host 'Fully restart WoW; new audio cannot be loaded using /reload alone.'
